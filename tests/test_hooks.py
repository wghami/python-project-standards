"""Local hooks are installed (HK-1)."""

from conftest import Repo
from project_standards.hooks import STAGES, check


def test_missing_hooks_are_reported(repo: Repo) -> None:
    assert len(check(repo.git)) == len(STAGES)


def test_installed_hooks_pass_and_foreign_hooks_fail(repo: Repo) -> None:
    hooks = repo.path / ".git" / "hooks"
    for stage in STAGES:
        (hooks / stage).write_text("#!/bin/sh\n# File generated by pre-commit\n")
    assert check(repo.git) == []
    (hooks / "pre-push").write_text("#!/bin/sh\necho custom\n")
    assert check(repo.git) == [
        "git hook 'pre-push' is not installed: run `uv run pre-commit install`"
    ]
